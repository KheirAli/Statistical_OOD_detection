def run_config(cfg_dict: dict, device: str) -> dict:
    ddad_cfg = load_ddad_config(cfg_dict["name"])
    ddad_cfg.model.device = device
    print(f"[ddad-multi] loading UNet for {cfg_dict['name']}…", flush=True)
    unet = load_ddad_unet(ddad_cfg)
    print(f"[ddad-multi] loading feature extractor…", flush=True)
    fe = domain_adaptation(unet, ddad_cfg, fine_tune=False)
    fe.eval()

    per_sample: List[dict] = []
    # For pooled DDAD-style computation
    all_cropped_preds: List[np.ndarray] = []
    all_cropped_gts: List[np.ndarray] = []

    with torch.no_grad():
        for sample in cfg_dict["samples"]:
            recons = load_reconstructions(
                results_dir=cfg_dict["results_dir"],
                sample_name=sample,
                test_origin=cfg_dict["test_origin"],
                num_patches=1, bottom_suffix="4",
            )  # (N, H, W, 3) uint8
            label = load_label_image(
                results_dir=cfg_dict["results_dir"],
                sample_name=sample,
                test_origin=cfg_dict["test_origin"],
                bottom_suffix="4",
            )  # (H, W, 3) uint8
            sample_id = parse_sample_id(sample)
            gt = cfg_dict["gt_loader"](sample_id)  # (256, 256) binary

            label_t = uint8_to_tensor(label, device)
            # Per-recon heat_map, averaged
            heats = []
            for i in range(recons.shape[0]):
                recon_t = uint8_to_tensor(recons[i], device)
                hm = heat_map(recon_t, label_t, fe, ddad_cfg)
                # hm is (1, 1, H, W) or similar; collapse to (H, W)
                hm_np = hm.squeeze().detach().cpu().numpy()
                if hm_np.ndim == 3:  # (C, H, W) — reduce to (H, W) via mean
                    hm_np = hm_np.mean(axis=0)
                heats.append(hm_np)
            mean_heat = np.mean(np.stack(heats, axis=0), axis=0)

            # Resize mean_heat to 256 if needed
            if mean_heat.shape != (256, 256):
                mean_heat = np.array(
                    Image.fromarray(mean_heat.astype(np.float32)).resize(
                        (256, 256), Image.BILINEAR
                    )
                )

            # Our-style metric: per-image AUC, full 256
            per_image_auc = pixel_auc(mean_heat, gt)

            # DDAD-style: center-crop 224, accumulate for pooling
            heat_c = center_crop_224(mean_heat)
            gt_c = center_crop_224(gt)
            all_cropped_preds.append(heat_c)
            all_cropped_gts.append(gt_c)

            per_sample.append({
                "sample": sample,
                "px_auc_full256": per_image_auc,
                "gt_positive_frac_256": float(gt.mean()),
            })
            print(f"  {sample}: Px_full256={per_image_auc:.4f}", flush=True)

    # Pooled (DDAD-style) on center-cropped
    pooled_pred = np.concatenate([p.ravel() for p in all_cropped_preds])
    pooled_gt = np.concatenate([g.ravel() for g in all_cropped_gts])
    pooled_auc = pixel_auc(pooled_pred, pooled_gt)

    per_image_aucs = [s["px_auc_full256"] for s in per_sample
                      if not np.isnan(s["px_auc_full256"])]
    mean_per_image = float(np.mean(per_image_aucs)) if per_image_aucs else None
    std_per_image = float(np.std(per_image_aucs)) if per_image_aucs else None

    del fe, unet
    torch.cuda.empty_cache()

    return {
        "config": cfg_dict["name"],
        "n_samples": len(per_sample),
        "mean_px_auc_per_image_full256": mean_per_image,
        "std_px_auc_per_image_full256": std_per_image,
        "pooled_px_auc_ddad_style_224crop": float(pooled_auc)
            if not np.isnan(pooled_auc) else None,
        "per_sample": per_sample,
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--output", required=True)
    p.add_argument("--device", default="cuda")
    args = p.parse_args()

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)

    report = {"runs": []}
    for cfg_dict in CONFIGS:
        print(f"\n[ddad-multi] === {cfg_dict['name']} ===", flush=True)
        r = run_config(cfg_dict, device=args.device)
        report["runs"].append(r)

    out.write_text(json.dumps(report, indent=2, default=str))
    print(f"\n[ddad-multi] wrote {out}", flush=True)

    # Summary
    print()
    print(f"{'config':<12} {'N':<4} {'mean per-image Px (256)':<28} {'pooled Px (224-crop)':<22}")
    print("-" * 70)
    for r in report["runs"]:
        m = r["mean_px_auc_per_image_full256"]
        p_ = r["pooled_px_auc_ddad_style_224crop"]
        m_s = f"{m:.4f} ± {r['std_px_auc_per_image_full256']:.4f}" if m is not None else "—"
        p_s = f"{p_:.4f}" if p_ is not None else "—"
        print(f"{r['config']:<12} {r['n_samples']:<4} {m_s:<28} {p_s:<22}")


if __name__ == "__main__":
    main()
