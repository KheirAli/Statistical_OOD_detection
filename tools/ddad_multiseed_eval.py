"""B2: DDAD's heatmap scorer applied to N averaged reconstructions.

The single make-or-break experiment per docs/research_roadmap.md.

Our cached `results_patches_ddad_native*/` already contains 20 seeds per image,
all generated by DDAD's own sampler. DDAD R1 uses only 1 of those 20. This
script runs DDAD's `heat_map` scorer on each of the 20 recons per image,
averages the anomaly maps, and reports AUC under BOTH methodologies:
  - DDAD-style: pooled pixel AUROC across all images, 224-center-crop
  - Our-style: per-image AUC, then mean, full 256

Compare to:
  - DDAD R1-faces:  0.558 (pooled, 224, 1 seed)
  - PMF no-PCA faces: 0.820 (mean, 256, 20 seeds)
  - variance-only faces: 0.869 (mean, 256, 20 seeds)

If DDAD-multi-seed on faces jumps into the 0.80+ range (under either
methodology), our wins are primarily from multi-sampling, not from our
scoring math. Paper needs to reframe. If DDAD-multi stays in the 0.55-0.70
range, our scoring math is adding real value.

Usage:
    python tools/ddad_multiseed_eval.py --output results_eval/ddad_multiseed/report.json
"""
